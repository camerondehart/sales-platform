#!/usr/bin/env node
/**
 * Night sky (switch night_sky): at night the page's text turns light to sit on the dark sky,
 * so every LIGHT surface (cards, forms, buttons, menus, the Concierge…) has to put the
 * daytime ink back for what's inside it. This finds every rule in app/globals.css that
 * paints a light background and writes the list into the block between the markers at the
 * end of the file.
 *
 *   node scripts/night-surfaces.cjs           rewrite the list
 *   node scripts/night-surfaces.cjs --check   exit 1 if the list is out of date (unit check)
 *
 * Run it after adding a light surface (a new card, pill or form) to the customer pages.
 */
const fs = require("fs");
const path = require("path");
const FILE = path.join(__dirname, "..", "app", "globals.css");
const START = "/* night-surfaces:start (generated by scripts/night-surfaces.cjs; don't edit by hand) */";
const END = "/* night-surfaces:end */";

function splitTop(s) {
  const out = [];
  let depth = 0, cur = "";
  for (const ch of s) {
    if (ch === "(") depth++;
    if (ch === ")") depth--;
    if (ch === "," && depth === 0) { out.push(cur); cur = ""; } else cur += ch;
  }
  out.push(cur);
  return out;
}

function isLight(v) {
  if (/var\(--(white|surface|paper|cream|surface-alt)\)/.test(v)) return true;
  if (/#(fff|ffffff|f9f9f8|fafafa|fdfdfb|fbfbf9|f7f7f5|f6f6f3|f4f4f1|fcfcfa|f8f8f6|fefefe|fbf9f4|faf8f2|f2f4ef)\b/i.test(v)) return true;
  for (const m of v.matchAll(/rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*([\d.]+))?\)/g)) {
    const a = m[4] ? parseFloat(m[4]) : 1;
    if (Math.min(+m[1], +m[2], +m[3]) >= 225 && a >= 0.55) return true;
  }
  return false;
}

/** Staff-only parts never get the night look, so they're left out of the list. */
const STAFF = /admin|data-admin-theme|\.esc-|\.help-|\.an-|\.kpi|settings|\.tpl-|\.al-|\.ap-|\.flag-|\.ent-|\.dc-|\.cc-|\.email-preview|\.cv-|\.export-btn|\.code-row|\.evn-|^html\b|^body|^:root/;

/** Light by day but repainted dark by the night rules themselves (keep them out of the list). */
const DARK_AT_NIGHT = new Set([".home-shop"]);

function surfaces(css) {
  const cut = css.indexOf(START);
  let src = cut >= 0 ? css.slice(0, cut) : css;
  src = src.replace(/\/\*[\s\S]*?\*\//g, "");
  const set = new Set();
  for (const m of src.matchAll(/([^{}@;]+)\{([^{}]*)\}/g)) {
    const sel = m[1], body = m[2];
    const paints = body.split(";").some((d) => {
      const mm = d.trim().match(/^background(?:-color)?\s*:([\s\S]*)$/);
      return mm && isLight(mm[1]);
    });
    if (!paints) continue;
    for (let s of splitTop(sel)) {
      s = s.trim().replace(/\s+/g, " ");
      if (!s || /::|:before|:after|^(from|to)$|^[\d.]+%/.test(s) || STAFF.test(s) || DARK_AT_NIGHT.has(s)) continue;
      set.add(s);
    }
  }
  return [...set].sort();
}

function block(list) {
  return `${START}
/* Light surfaces (dusk-tinted at night) get a slightly deeper ink so text stays easy to read. :where() keeps this at zero specificity,
   so each surface's own colours still win; only what it would inherit from the page changes. */
:where(html[data-night]) :where(
  ${list.join(",\n  ")}
) {
  --ink: #434a56; --ink-soft: #565e6b; --ink-faint: #7a8291; --dark-grey: #434a56; --grey: #565e6b; --light-grey: #8b93a2;
  --rule: #9aa2b3; --rule-soft: #b6bdcc; --accent-strong: #557f27; --mint-deep: #087a67; --yellow-deep: #6a6c20;
  color: var(--ink);
}
${END}`;
}

const css = fs.readFileSync(FILE, "utf8");
const next = block(surfaces(css));
const s = css.indexOf(START), e = css.indexOf(END);
const current = s >= 0 && e > s ? css.slice(s, e + END.length) : "";
if (process.argv.includes("--check")) {
  const ok = current === next;
  console.log(ok ? `night surfaces up to date (${surfaces(css).length})` : "FAIL night surfaces out of date: run node scripts/night-surfaces.cjs");
  process.exit(ok ? 0 : 1);
}
const out = current ? css.replace(current, next) : css.replace(/\s*$/, "\n\n") + next + "\n";
fs.writeFileSync(FILE, out);
console.log(`wrote ${surfaces(css).length} night surfaces`);
